"""Generate the WebGPU dispatch table from the vendored webgpu-headers.

Every `wgpu*` entry point declared by upstream gets a function pointer, a
lookup, and a macro that redirects calls to that pointer. Run this after
updating ThirdParty/webgpuheaders and commit the result:

    python3 Rendering/WebGPU/generate_proc_dispatch.py
    clang-format -i Rendering/WebGPU/Private/vtkWebGPUProcDispatch.[ch]xx
"""

import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
HEADER = HERE.parent.parent / "ThirdParty/webgpuheaders/vtkwebgpuheaders/include/webgpu/webgpu.h"
OUT_DIR = HERE / "Private"

LICENSE = """// SPDX-FileCopyrightText: Copyright (c) Ken Martin, Will Schroeder, Bill Lorensen
// SPDX-License-Identifier: BSD-3-Clause
// Generated by Rendering/WebGPU/generate_proc_dispatch.py. Do not edit.
"""

DECL = re.compile(r"^WGPU_EXPORT\s+.*?\b(wgpu[A-Za-z0-9_]+)\s*\(", re.MULTILINE)


def entry_points(header_text):
    names = list(dict.fromkeys(DECL.findall(header_text)))
    if not names:
        raise SystemExit("no wgpu* entry points found; has the header layout changed?")
    return names


def write_header(names):
    lines = [
        LICENSE,
        "#ifndef vtkWebGPUProcDispatch_h",
        "#define vtkWebGPUProcDispatch_h",
        "",
        '// This header is forced into every source ahead of their own includes, so',
        '// it must not reach a VTK header that defines VTK_DEPRECATION_LEVEL: that',
        '// would fix the level before a source can set its own. Hence the export',
        '// decoration below instead of vtkRenderingWebGPUModule.h.',
        '#include "vtkABINamespace.h" // for the ABI namespace macros',
        '#include "vtk_wgpu.h"        // for the entry point typedefs',
        "",
        "#if defined(_WIN32) && !defined(VTKRENDERINGWEBGPU_STATIC_DEFINE)",
        "#ifdef vtkRenderingWebGPU_EXPORTS",
        "#define VTK_WEBGPU_PROC_EXPORT __declspec(dllexport)",
        "#else",
        "#define VTK_WEBGPU_PROC_EXPORT __declspec(dllimport)",
        "#endif",
        "#elif defined(__GNUC__) || defined(__clang__)",
        '#define VTK_WEBGPU_PROC_EXPORT __attribute__((visibility("default")))',
        "#else",
        "#define VTK_WEBGPU_PROC_EXPORT",
        "#endif",
        "",
        "/**",
        " * The implementation's entry points, resolved at runtime.",
        " *",
        " * VTK does not link an implementation, so the `wgpu*` names it calls are not",
        " * bound at link time. This table holds the pointers the proc table resolved,",
        " * and the macros below redirect every call to it. The build forces this header",
        " * into the module's own sources only, so nothing leaks into installed headers",
        " * or into what consumers compile.",
        " *",
        " * Emscripten links the implementation into the module, so the macros are not",
        " * defined there and the calls bind normally.",
        " */",
        "",
        "#if !defined(__EMSCRIPTEN__)",
        "",
        "VTK_ABI_NAMESPACE_BEGIN",
        "struct vtkWebGPUProcDispatch",
        "{",
    ]
    for name in names:
        member = name[len("wgpu"):]
        lines.append(f"  WGPUProc{member} {member} = nullptr;")
    lines += [
        "};",
        "",
        "/**",
        " * The one dispatch table. Populated by vtkWebGPUProcDispatchResolve().",
        " */",
        "extern VTK_WEBGPU_PROC_EXPORT vtkWebGPUProcDispatch vtkWebGPUProcs;",
        "",
        "/**",
        " * Resolve every entry point through the given proc address function.",
        " * Returns the name of the first one that could not be resolved, or nullptr on",
        " * success - a partially resolved table means the library is not a WebGPU",
        " * implementation VTK can use.",
        " */",
        "VTK_WEBGPU_PROC_EXPORT const char* vtkWebGPUProcDispatchResolve(",
        "  WGPUProc (*getProcAddress)(WGPUStringView));",
        "VTK_ABI_NAMESPACE_END",
        "",
        "// clang-format off",
    ]
    for name in names:
        member = name[len("wgpu"):]
        lines.append(f"#define {name} vtkWebGPUProcs.{member}")
    lines += [
        "// clang-format on",
        "",
        "#endif // !__EMSCRIPTEN__",
        "",
        "#endif // vtkWebGPUProcDispatch_h",
        "// VTK-HeaderTest-Exclude: vtkWebGPUProcDispatch.h",
        "",
    ]
    (OUT_DIR / "vtkWebGPUProcDispatch.h").write_text("\n".join(lines))


def write_source(names):
    lines = [
        LICENSE,
        '#include "Private/vtkWebGPUProcDispatch.h"',
        "",
        "#if !defined(__EMSCRIPTEN__)",
        "",
        "VTK_ABI_NAMESPACE_BEGIN",
        "vtkWebGPUProcDispatch vtkWebGPUProcs;",
        "",
        "const char* vtkWebGPUProcDispatchResolve(WGPUProc (*getProcAddress)(WGPUStringView))",
        "{",
        "  if (getProcAddress == nullptr)",
        "  {",
        '    return "wgpuGetProcAddress";',
        "  }",
        "  vtkWebGPUProcDispatch resolved;",
    ]
    for name in names:
        member = name[len("wgpu"):]
        lines += [
            f'  resolved.{member} = reinterpret_cast<WGPUProc{member}>(',
            f'    getProcAddress(WGPUStringView{{ "{name}", WGPU_STRLEN }}));',
            f"  if (resolved.{member} == nullptr)",
            "  {",
            f'    return "{name}";',
            "  }",
        ]
    lines += [
        "  vtkWebGPUProcs = resolved;",
        "  return nullptr;",
        "}",
        "VTK_ABI_NAMESPACE_END",
        "",
        "#endif // !__EMSCRIPTEN__",
        "",
    ]
    (OUT_DIR / "vtkWebGPUProcDispatch.cxx").write_text("\n".join(lines))


def main():
    if not HEADER.exists():
        raise SystemExit(f"cannot find {HEADER}")
    names = entry_points(HEADER.read_text())
    write_header(names)
    write_source(names)
    print(f"generated dispatch for {len(names)} entry points")
    return 0


if __name__ == "__main__":
    sys.exit(main())
